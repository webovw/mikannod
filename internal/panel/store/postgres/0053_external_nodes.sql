-- External client-side Xray outbounds imported by the panel admin. They are not managed
-- Mikan nodes: no node agent, traffic accounting or server-side listener is implied.
-- +goose Up
CREATE TABLE external_nodes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 120),
  protocol TEXT NOT NULL CHECK (protocol IN ('vless','vmess','trojan','shadowsocks')),
  uri TEXT NOT NULL,
  mihomo JSONB NOT NULL,
  source_json TEXT NOT NULL DEFAULT '',
  enabled SMALLINT NOT NULL DEFAULT 1 CHECK (enabled IN (0,1)),
  in_auto SMALLINT NOT NULL DEFAULT 1 CHECK (in_auto IN (0,1)),
  sort BIGINT NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);
CREATE INDEX external_nodes_enabled_sort ON external_nodes(enabled, sort, id);

